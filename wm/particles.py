def antiparticle(p: Particle) -> Particle:
    """Античастица: заряд и аромат с противоположным знаком (CPT)."""
    if p.kind == "photon" or p.symbol in ("g",):
        return p  # собственные античастицы
    sym = ANTI.get(p.symbol)
    if sym is None:
        return p
    for q in PARTICLES:
        if q.symbol == sym:
            return q
    return Particle(p.symbol + "̄", "анти-" + p.name, p.mass_eV, -p.charge,
                    p.spin, p.kind, p.color, p.gen, p.lifetime_s, p.decays,
                    "антиузел: тот же синтез слоёв, знак заряда L4 инвертирован")


def particle_from_energy(E_eV: float) -> List[Particle]:
    """Какие узлы могут сконденсироваться при энергии E (правило E ≥ mc²).
    Возвращает все типы с массой ≤ E (от тяжёлых к лёгким)."""
    avail = [p for p in PARTICLES if 0.0 < p.mass_eV <= E_eV and p.kind != "hadron"]
    return sorted(avail, key=lambda p: -p.mass_eV)


def node_layers(p: Particle) -> dict:
    """Состояние 5 слоёв для узла типа p.
    Показывает, КАК частица «вкладывается» в субпространства."""
    return {
        "ВРЕМЯ (L0)": "фаза течёт со скоростью 1 (частица не в грав. яме)",
        "ЭНЕРГИЯ (L1)": f"E_узла = {p.mass_MeV:.4g} МэВ (заперта связностью узла)",
        "ВЕРОЯТНОСТЬ (L2)": f"|ψ|² = 1 (связанное состояние), спин {p.spin:g} = ветвление фазы",
        "ГРАВИТАЦИЯ (L3)": f"яма ∝ m (E=mc²): {p.mass_MeV/938.272:.3g} × протона",
        "ПОЛЯ (L4)": f"заряд {p.charge:+g}e" + (f", цвет {p.color}" if p.color else ""),
        "правило": p.rule,
    }


def mass_budget(hadron: str) -> str:
    """Бюджет массы адрона: масса кварков vs полная масса (QCD-энергия поля)."""
    quark_masses = {"u": 2.2e6, "d": 4.7e6, "s": 95.6e6, "c": 968.0e6, "b": 4180.0e6}
    comp = HADRON_COMPOSITION.get(hadron, "")
    qsum = 0.0
    for ch in comp:
        if ch in quark_masses:
            qsum += quark_masses[ch]
    p = BY_SYMBOL.get(hadron)
    if p is None:
        return f"{hadron}: нет в каталоге"
    qcd = p.mass_eV - qsum
    return (f"{p.symbol}: полная {p.mass_MeV:.4g} МэВ | кварки {qsum/1e6:.4g} МэВ "
            f"({qsum/p.mass_eV*100:.1f}%) | QCD-поле {qcd/1e6:.4g} МэВ "
            f"({qcd/p.mass_eV*100:.1f}%)")
