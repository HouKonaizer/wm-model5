"""
ЭЛЕМЕНТАРНЫЕ ЧАСТИЦЫ В МОДЕЛИ 5 СУБПРОСТРАНСТВ
==============================================
Частица = УЗЕЛ (синтез 5 слоёв) с фиксированным набором квантовых чисел:

  масса      -> энергия, запертая в узле (L1): E = m·c²  (MATTER_REST_MASS)
  заряд      -> источник поля в L4 (FIELD_DIPOLE, знак = частица/античастица)
  спин       -> фаза ψ в L2: спин-1/2 = два значения фазы (±),
                спин-1  = вектор поля (поляризация фотона),
                спин-0  = скаляр (Higgs: узел без фазовой структуры)
  цвет       -> 3 под-состояния поля L4 (красный/зелёный/голубой);
                кварк невидим вне цветового синглета (конфайнмент)
  поколение  -> энергетический порог конденсации (чем тяжелее, тем больше
                энергии нужно собрать в ячейке)
  аромат     -> тип узла; слабый канал позволяет узлу «перекристаллизоваться»
                (ν_е <-> ν_μ: осцилляции)

Правила:
  * Рождение: E_ячейки ≥ m·c²  (кристаллизация узла типа m)
  * Аннигиляция: узел + антиузел -> энергия + фотоны (L1 -> L4, E = 2mc²)
  * Распад: узел с избытком энергии -> набор более лёгких узлов
            (правило Ферми; время жизни = MATTER_LIFETIME · масштаб)
  * Конфайнмент: кварковый узел вне цветового синглета растит линейную
    потенциальную энергию поля (flux tube) -> рождает пару q q̄ (струя)
"""

from dataclasses import dataclass, field
from typing import Optional, List

# ============================================================
# ОПИСАНИЕ ЧАСТИЦЫ
# ============================================================

@dataclass(frozen=True)
class Particle:
    symbol: str            # обозначение
    name: str              # имя
    mass_eV: float         # масса, эВ
    charge: float          # заряд в единицах |e| (дробные = кварки)
    spin: float            # спин в ħ
    kind: str              # lepton | quark | gauge | scalar | hadron | photon
    color: str = ""        # "" (бесцветный) или r/g/b
    gen: int = 0           # поколение (1..3)
    lifetime_s: Optional[float] = None   # None = стабильный
    decays: tuple = field(default_factory=tuple)  # каналы распада (строки)
    rule: str = ""         # как узел выглядит в 5 слоях модели

    @property
    def mass_MeV(self) -> float:
        return self.mass_eV / 1e6


