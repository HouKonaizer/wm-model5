CHECKS = []


class Check:
    """Одна сверка: формула модели vs эксперимент."""
    __slots__ = ("cat", "name", "f_model", "f_phys", "v_model", "v_exp",
                 "src", "kind", "unit", "dev", "note")

    def __init__(self, cat, name, f_model, f_phys, v_model, v_exp,
                 src, kind, unit="", note=""):
        self.cat = cat
        self.name = name
        self.f_model = f_model      # уравнение в нотации модели (L0..L4)
        self.f_phys = f_phys        # стандартная физическая формула
        self.v_model = float(v_model)
        self.v_exp = float(v_exp)
        self.src = src              # источник экспериментального значения
        self.kind = kind            # correspondence | prediction | discrete
        self.unit = unit
        self.note = note
        if v_exp != 0:
            self.dev = (v_model - v_exp) / v_exp
        else:
            self.dev = float("nan")
        CHECKS.append(self)


def rel_err(v_model, v_exp):
    return (v_model - v_exp) / v_exp if v_exp != 0 else float("nan")


