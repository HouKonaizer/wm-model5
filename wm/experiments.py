    gamma_mu = G_F ** 2 * m_mu_GeV ** 5 / (192 * math.pi ** 3)   # ГэВ
    tau_mu_pred = HBAR_GEV_S / gamma_mu                            # с
    tau_mu_exp = 2.1969811e-6
    Check("Слабое", "время жизни мюона τ_μ (tree, без рад. поправок)",
          "1/τ = G_F²m_μ⁵/(192π³)  [узел μ -> e ν ν̄ через тяжёлую волну W]",
          "Γ_μ = G_F²m_μ⁵/192π³", tau_mu_pred, tau_mu_exp,
          "PDG 2024", "prediction", "с",
          "откл. −0.43% = известные радиативные поправки (не в tree); модель честна")

    # --- G_F из μ-распада (калибровка слабого канала) ---
    g_f_from_mu = math.sqrt(192 * math.pi ** 3 * HBAR_GEV_S / (tau_mu_exp * m_mu_GeV ** 5))
    Check("Слабое", "константа Ферми G_F из τ_μ (сверка с CODATA)",
          "G_F = sqrt(192π³·τ_μ·ħ/m_μ⁵)  [калибровка слабого канала L4]",
          "G_F из μ-распада", g_f_from_mu, G_F,
          "PDG 2024", "correspondence", "ГэВ⁻²",
          f"откл. {(g_f_from_mu-G_F)/G_F*100:+.2f}% = рад. поправки к μ")

    # --- τ нейтрона: CORRESPONDENCE (станд. формула PDG + числ. фаза) ---
    # 1/τ_n = G_F² V_ud² m_e⁵ (1+3λ²) F f₀ / (2π³)  [норм. ед.]
    m_e_GeV = 0.000510998950
    v_ud = 0.974
    lam = 1.2754          # g_A/g_V (измеренное)
    F_rad = 1.0239        # внешние радиативные поправки
    W0 = 1.0 + (M_N - M_P) / M_E          # в единицах m_e c²
    I_n = _phase_space_1d(W0)             # allowed-интеграл (численно, м_е-ед.)
    f0 = 1.7160           # фазовый интеграл PDG (W0 = 3.531, с рекоилом)
    gamma_n = (G_F ** 2 * v_ud ** 2 * m_e_GeV ** 5 * (1 + 3 * lam ** 2)
               * F_rad * f0) / (2 * math.pi ** 3)   # ГэВ
    tau_n_pred = HBAR_GEV_S / gamma_n
    tau_n_exp = 878.4
    Check("Слабое", "время жизни нейтрона τ_n (V_ud, λ, f₀ PDG)",
          "1/τ = G_F²V_ud²m_e⁵(1+3λ²)F·f₀/(2π³)  [узел n -> p e ν̄ (слабый)]",
          "станд. формула PDG", tau_n_pred, tau_n_exp,
          "PDG 2024", "correspondence", "с",
          f"V_ud={v_ud}, λ={lam}, F={F_rad}, f₀={f0}; "
          f"allowed-интеграл на сетке I={I_n:.3f}")


