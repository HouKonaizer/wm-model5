def fmt_dev(d):
    if math.isnan(d):
        return "—"
    return f"{d * 100:+.3f}%"


def write_audit_html(out_dir):
    """audit.html — офлайн-дашборд аудита (V2, 4 таба).

    Вшивает verification.json из out_dir в шаблон audit_template.html
    (маркеры /*__DATA__*/null и "/*__GEN__*/"); шаблон ищется в out_dir,
    затем в корне проекта. Зависимостей нет: чистый HTML+CSS+JS.
    """
    v_path = os.path.join(out_dir, "verification.json")
    if not os.path.isfile(v_path):
        raise FileNotFoundError(f"verification.json не найден: {v_path}")
    with open(v_path, "r", encoding="utf-8") as f:
        v = json.load(f)
    data_json = json.dumps(v, ensure_ascii=False, separators=(",", ":"))
    # защита от преждевременного закрытия <script> (\\/ — валидный JSON-экскейп)
    data_json = data_json.replace("</", "<\\/")
    tpl_path = os.path.join(out_dir, "audit_template.html")
    if not os.path.isfile(tpl_path):
        root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        alt = os.path.join(root, "audit_template.html")
        if os.path.isfile(alt):
            tpl_path = alt
    if not os.path.isfile(tpl_path):
        raise FileNotFoundError(
            "audit_template.html не найден (в out_dir и в корне проекта)")
    with open(tpl_path, "r", encoding="utf-8") as f:
        tpl = f.read()
    marker = "/*__DATA__*/null"
    if marker not in tpl:
        raise RuntimeError("В шаблоне audit_template.html нет маркера /*__DATA__*/null")
    gen = datetime.date.today().isoformat()
    html = tpl.replace(marker, data_json).replace('"/*__GEN__*/"', f'"{gen}"')
    out_path = os.path.join(out_dir, "audit.html")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(html)
    print(f"Аудит-дашборд: {out_path} "
          f"({os.path.getsize(out_path) / 1024:.0f} КБ) — открыть в браузере")


