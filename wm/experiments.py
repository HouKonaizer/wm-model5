def check_discrete():
    # --- D1: время у массы медленнее (решёточный аналог грав. дилатации) ---
    from . import model as M
    v = M.Volume3D(size=20, seed=42)
    s = v.size
    c = 10
    idx = lambda i, j, k: i * s * s + j * s + k   # плоский индекс (C-порядок)
    for i in range(c - 2, c + 3):
        for j in range(c - 2, c + 3):
            for k in range(c - 2, c + 3):
                if (i - c) ** 2 + (j - c) ** 2 + (k - c) ** 2 < 9:
                    v.matter[idx(i, j, k)] = True
                    v.energy[idx(i, j, k)] = 15.0
    for _ in range(40):
        v.step()
    near = float(v.time_rate[idx(c, c, c)])
    mid = float(v.time_rate[idx(c + 3, c, c)])   # d=3: сразу за шаром (d²<9)
    far = float(v.time_rate[idx(c + 6, c, c)])
    mono = (near < mid) and (mid < far)
    Check("Реш", "D1: время у массы (Volume3D, 40 шагов)",
          "time_rate = (1+0.3·grav)(1−0.1·E)  [L0+L3]",
          "ГР: dτ = √(1+2Φ/c²)·dt < dt у массы",
          1.0 if mono else 0.0, 1.0,
          "ГР (качественно)", "discrete", "—",
          f"time_rate: near={near:.3f} mid={mid:.3f} far={far:.3f}; "
          f"монотонность = качественное совпадение с ГР; величина замедления — "
          f"некалиброванный параметр модели")

    # --- D2: свободный RLC: RK4 на решётке vs точный затухающий период ---
    L_h, C_f, R_o = 1e-3, 1e-6, 10.0
    a_d = R_o / L_h
    b_d = 1.0 / (L_h * C_f)
    w0 = math.sqrt(b_d)
    wd = math.sqrt(max(b_d - a_d ** 2 / 4.0, 0.0))
    f_damp = wd / (2.0 * math.pi)
    dt = 1.0e-6
    x, vel, t = 1.0, 0.0, 0.0
    prev = x
    crossings = []
    for _ in range(20000):
        k1x, k1v = vel, -a_d * vel - b_d * x
        k2x, k2v = vel + 0.5 * dt * k1v, -a_d * (vel + 0.5 * dt * k1v) - b_d * (x + 0.5 * dt * k1x)
        k3x, k3v = vel + 0.5 * dt * k2v, -a_d * (vel + 0.5 * dt * k2v) - b_d * (x + 0.5 * dt * k2x)
        k4x, k4v = vel + dt * k3v, -a_d * (vel + dt * k3v) - b_d * (x + dt * k3x)
        x += dt / 6.0 * (k1x + 2 * k2x + 2 * k3x + k4x)
        vel += dt / 6.0 * (k1v + 2 * k2v + 2 * k3v + k4v)
        t += dt
        if prev < 0.0 <= x:
            crossings.append(t - dt + dt * (-prev) / (x - prev))
        prev = x
    # первые 5 периодов (затухание e^{−Rt/2L}: сигнал гаснет за ~10 мс)
    gaps = [crossings[i + 1] - crossings[i] for i in range(min(5, len(crossings) - 1))]
    f_num = float(np.median(1.0 / np.asarray(gaps))) if gaps else float("nan")
    Check("Реш", "D2: свободный RLC (L=1 мГн, C=1 мкФ, R=10 Ом)",
          "x'' + (R/L)x' + (1/LC)x = 0  [L1: осцилляция узлов L4]",
          "f_d = √(ω₀²−(R/2L)²)/2π", f_num, f_damp,
          "точное затухающее решение", "discrete", "Гц",
          f"RK4, dt={dt:g} с (ωdt≈{w0 * dt:.3f}); откл. = погрешность схемы; "
          f"f₀={w0 / (2 * math.pi):.1f} Гц (без затухания)")

    # --- D3: двойная щель: период полос vs λL/d ---
    lam = 500e-9
    d_slit = 50e-6
    L_scr = 1.0
    ys = np.linspace(-0.05, 0.05, 8001)
    A = 0.0
    for s in (-d_slit / 2.0, d_slit / 2.0):
        r = np.sqrt((ys - s) ** 2 + L_scr ** 2)
        A = A + np.exp(1j * 2.0 * math.pi * r / lam)
    I = (A * A.conjugate()).real
    maxs = [ys[i] for i in range(1, len(ys) - 1)
            if I[i] > I[i - 1] and I[i] > I[i + 1]]
    gap = float(np.median(np.diff(np.asarray(maxs)))) if len(maxs) >= 3 else float("nan")
    Check("Реш", "D3: двойная щель (λ=500 нм, d=50 мкм, L=1 м)",
          "A = Σ_s exp(ikr_s), I = |A|²  [L2: юнитарная суперпозиция]",
          "Δy = λL/d", gap, lam * L_scr / d_slit,
          "фраунгоферова дифракция", "discrete", "м",
          f"сетка 8001 точка; период полос; макс. полос={len(maxs)}")


def check_dynamics():
    """Динамика частиц на решётке: спин/Pauli/Бозе (D4), цепочки распада (D5),
    кварковая струна/конфайнмент (D6)."""
    from . import model as M

    # --- D4: спин ↑/↓; Pauli-принцип (фермионы); бозе-стек (бозоны) ---
    v = M.Volume3D(size=12, seed=7)
    ok_a = v.inject_particle((5, 5, 5), "n", spin=1)
    ok_b = v.inject_particle((5, 5, 5), "n", spin=1)    # тот же спин → Pauli
    ok_c = v.inject_particle((6, 5, 5), "n", spin=0)
    ok_d = v.inject_particle((6, 5, 5), "n", spin=1)    # разный спин → OK
    oks_g = [v.inject_particle((7, 5, 5), "γ") for _ in range(3)]  # бозе-стек
    s = v.size
    fl = lambda i, j, k: (i * s + j) * s + k
    n_same = int(v.stack[fl(5, 5, 5)])
    n_diff = int(v.stack[fl(6, 5, 5)])
    stack_g = int(v.stack[fl(7, 5, 5)])
    total_nodes = int(v.stack.sum())
    d4_ok = (ok_a and not ok_b and ok_c and ok_d and all(oks_g)
             and n_same == 1 and n_diff == 2 and stack_g == 3
             and v.pauli_blocks == 1 and total_nodes == 6)
    Check("Реш", "D4: спин ↑/↓: Pauli (фермионы) и бозе-стек",
          "2 слота/ячейку (слот = спин); фермион → в свободный слот; бозон → стек ≤3",
          "Pauli: 1 фермион на квант. состояние; бозе: N бозонов в одном",
          1.0 if d4_ok else 0.0, 1.0,
          "квантовая статистика", "discrete", "—",
          f"2 n↑ в 1 ячейке: {n_same} узел (2-й {'' if ok_b else 'заблокирован'}); "
          f"2 n со спинами 0/1: {n_diff}; 3 γ: стек={stack_g}; "
          f"pauli_blocks={v.pauli_blocks}; всего узлов={total_nodes}")

    # --- D5: цепочка распада τ⁻ → (e⁻|μ⁻|π±) → … → e⁻ (стабильный конец) ---
    v = M.Volume3D(size=12, seed=11)
    v.inject_particle((5, 5, 5), "τ⁻", spin=0)
    v.inject_particle((8, 8, 8), "τ⁻", spin=1)
    for _ in range(1500):
        v.step()
    evs = v.decay_events
    # Цепочка: τ → дочерняя → … (связь через parent-ид события)
    chains = []
    for e in evs:
        if e["from"] != "τ⁻":
            continue
        chain = [e]
        cur = e
        for _ in range(10):
            kids = [d for d in evs
                    if d.get("parent") == cur["id"] and d["t"] > cur["t"]]
            if not kids:
                break
            cur = kids[0]
            chain.append(cur)
        chains.append(chain)
    # Свойство: каждый распад τ/μ/π даёт дочерний узел, и вся цепочка
    # заканчивается стабильным e⁻ (e⁻ никогда не распадается).
    all_end_in_e = all(c[-1].get("to") == "e⁻" for c in chains) if chains else False
    has_daughter = all(e.get("to") is not None
                       for e in evs if e["from"] in ("τ⁻", "μ⁻", "π±"))
    e_never = not any(e["from"] == "e⁻" for e in evs)
    code_e = M.TYPE_CODE["e⁻"]
    e_alive = bool(((v.node_t == code_e) | (v.node_t2 == code_e)).any())
    d5_ok = len(chains) == 2 and has_daughter and all_end_in_e and e_never and e_alive
    depths = [len(c) for c in chains]
    Check("Реш", "D5: цепочка распада τ⁻ → … → e⁻ (Volume3D)",
          "τ(50)→e⁻/μ⁻(139)/π±(114)→…→e⁻(стабильно); лог-сжатие τ_модель",
          "PDG: τ→eνν 17.8%, τ→μνν 17.4%, τ→адроны 64.8% → e⁻; e⁻ стабильна",
          1.0 if d5_ok else 0.0, 1.0,
          "PDG (цепочка до стабильного e⁻)", "discrete", "—",
          f"τ={len(chains)}; глубины (число распадов)={depths}; "
          f"все концы в e⁻={all_end_in_e}; e⁻ не распадается={e_never}, "
          f"жива={e_alive}; τ-модель=50, μ=139, π=114 шагов (лог-сжатие 15 орд.)")

    # --- D6: кварковая струна: стягивание + разрыв (конфайнмент) ---
    v = M.Volume3D(size=12, seed=13)
    v.inject_quark_pair((3, 6, 6), dist=2)
    for _ in range(400):
        v.step()
        if not v.strings:
            break
    u_idx = [i for i in range(v.n)
             if v.node_t[i] in (M.TYPE_CODE["u"], M.TYPE_CODE["ū"])
             or v.node_t2[i] in (M.TYPE_CODE["u"], M.TYPE_CODE["ū"])]
    if u_idx and v.strings:
        st = v.strings[0]
        ax, ay, az = st["a"] // (s * s), (st["a"] // s) % s, st["a"] % s
        bx, by, bz = st["b"] // (s * s), (st["b"] // s) % s, st["b"] % s
        def td(p, q):
            d = abs(p - q)
            return min(d, s - d)
        d_end = float((td(ax, bx) ** 2 + td(ay, by) ** 2 + td(az, bz) ** 2) ** 0.5)
    else:
        d_end = 0.0   # аннигиляция u+ū → энергия (струна исчезла)
    contract_ok = d_end <= 2
    v2 = M.Volume3D(size=12, seed=17)
    v2.inject_quark_pair((3, 6, 6), dist=5)   # ≥ STRING_BREAK(4)
    for _ in range(80):
        v2.step()
    broke = any(e.get("type") == "string_break" for e in v2.decay_events)
    d6_ok = contract_ok and broke and v2.n_quarks_created >= 4
    Check("Реш", "D6: кварковая струна (конфайнмент: σ·d, разрыв при d≥4)",
          "струна u—ū: стягивание 1 шаг/шаг; d≥4 → разрыв + пара u ū",
          "конфайнмент: V(r)=σr; σ≈0.9 ГэВ/фм → рождение пары (струя)",
          1.0 if d6_ok else 0.0, 1.0,
          "качественно: QCD-струя (lattice-QCD)", "discrete", "—",
          f"пара d=2: конец d={d_end:.0f} (стянуто/аннигилировано); "
          f"пара d=5: разрыв={broke}, создано кварков={v2.n_quarks_created}")


