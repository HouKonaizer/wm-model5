def quantum_h_l2(n_box: float = 7.0) -> dict:
    """Основное состояние 1s кулоновского поля в модельных единицах (1D s-wave).

    L2-схема модели: FD-оператор H = −(ħ²/2m_e)·D² + V (тот же stencil/symbol,
    что в SSFM-ядре _update_probability_uni), g = ħ²/(2m_e) (SI-карта).
    3D-запуск невозможен (S > 2·a0 ≥ 3.5e13 яч.) — редукция к 1D для s-wave:
    −g·u''(r) − K/√(r²+eps²)·u = E·u, u(0) = 0 (u = r·R(r)). Trial-функция
    u = r·e^(−r/a0) (точное собственное состояние континуума); E — Rayleigh
    quotient по модельному FD-stencil'у.

    α-якорь (S1): K·U·h = α·ħ·c ⇒ модельный α = физический α:
    a0 = ħ²/(m_e·K) = 10344.26 яч. = 5.291772e-11 м;
    E1 = m_e·K²/(2ħ²) = 13.6057 эВ (замкнутая форма). Отклонение FD-значения
    от замкнутой = погрешность решёточной схемы (softening + коробка) —
    честный дискретный расчёт, а не классическая орбита (P5 — структурный
    аналог: r0 = 15.347 фм, E_bind = 3.311e-2 эВ).
    """
    from . import model as M
    m_e = M_E * C ** 2 / M.SI_U_J
    hbar = HBAR / (M.SI_U_J * M.SI_DT_S)
    g = hbar ** 2 / (2.0 * m_e)
    K = M.COULOMB_K
    a0 = hbar ** 2 / (m_e * K)
    L = int(n_box * a0)
    r = np.arange(0, L + 1, dtype=float)
    V = -K / np.sqrt(r * r + M.COULOMB_SOFT ** 2)
    u = r * np.exp(-r / a0)
    u2 = np.zeros_like(u)
    u2[1:-1] = u[2:] - 2.0 * u[1:-1] + u[:-2]
    E1 = float((-g * (u * u2).sum() + (V * u * u).sum()) / (u * u).sum())
    E1_closed = -m_e * K ** 2 / (2.0 * hbar ** 2)
    return {
        "g": g,
        "a0_cells": a0,
        "a0_m": a0 * M.SI_H_M,
        "L": L,
        "E1_U": E1,
        "E1_eV": abs(E1) * M.SI_U_MEV * 1e6,
        "E1_closed_eV": abs(E1_closed) * M.SI_U_MEV * 1e6,
    }


